-- Run this in Supabase SQL editor to set up the inventory table

create table if not exists public.inventory (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  product_id text not null,
  size text,
  stock integer not null default 0
);

-- If the table pre-dates the size column (unique only on product_id), migrate it
alter table public.inventory add column if not exists size text;
alter table public.inventory drop constraint if exists inventory_product_id_key;

create unique index if not exists inventory_product_id_size_idx on public.inventory (product_id, size);
create index if not exists inventory_product_id_idx on public.inventory (product_id);

